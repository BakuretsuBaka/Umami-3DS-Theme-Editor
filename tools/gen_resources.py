#!/usr/bin/env python3
"""Regenerates the strongly typed *.Designer.cs wrappers from the neutral .resx files.

Usage: python3 tools/gen_resources.py
The wrappers mirror what Visual Studio's ResXFileCodeGenerator produces, so the project builds the same way
on every platform without needing the designer.
"""
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "ThemeEditor.App", "Localization")
NAMESPACE = "ThemeEditor.App.Localization"

TEMPLATE = '''//------------------------------------------------------------------------------
// <auto-generated>
//     Generated by tools/gen_resources.py from {resx}. Do not edit by hand.
// </auto-generated>
//------------------------------------------------------------------------------

namespace {ns} {{
    using System;

    /// <summary>Strongly-typed accessor for the {cls} resources.</summary>
    public class {cls} {{

        private static global::System.Resources.ResourceManager resourceMan;

        private static global::System.Globalization.CultureInfo resourceCulture;

        internal {cls}() {{
        }}

        [global::System.ComponentModel.EditorBrowsableAttribute(global::System.ComponentModel.EditorBrowsableState.Advanced)]
        public static global::System.Resources.ResourceManager ResourceManager {{
            get {{
                if (object.ReferenceEquals(resourceMan, null)) {{
                    global::System.Resources.ResourceManager temp = new global::System.Resources.ResourceManager("{ns}.{cls}", typeof({cls}).Assembly);
                    resourceMan = temp;
                }}
                return resourceMan;
            }}
        }}

        [global::System.ComponentModel.EditorBrowsableAttribute(global::System.ComponentModel.EditorBrowsableState.Advanced)]
        public static global::System.Globalization.CultureInfo Culture {{
            get {{
                return resourceCulture;
            }}
            set {{
                resourceCulture = value;
            }}
        }}
{props}
    }}
}}
'''

PROP = '''
        /// <summary>Looks up the localized string "{key}".</summary>
        public static string {key} {{
            get {{
                return ResourceManager.GetString("{key}", resourceCulture);
            }}
        }}
'''


def keys(path):
    tree = ET.parse(path)
    out = []
    for d in tree.getroot().findall("data"):
        name = d.get("name")
        if d.get("type") or d.get("mimetype"):
            continue
        if re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", name) and name not in ("Name1", "Color1", "Bitmap1", "Icon1"):
            out.append(name)
    return sorted(set(out))


for cls in ("MainResources", "ThemeResources"):
    resx = os.path.join(ROOT, cls + ".resx")
    props = "".join(PROP.format(key=k) for k in keys(resx))
    with open(os.path.join(ROOT, cls + ".Designer.cs"), "w", encoding="utf-8", newline="\n") as f:
        f.write(TEMPLATE.format(resx=cls + ".resx", ns=NAMESPACE, cls=cls, props=props))
    print(cls, len(keys(resx)), "keys")
